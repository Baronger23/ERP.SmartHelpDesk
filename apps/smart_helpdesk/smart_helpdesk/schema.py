"""Version-controlled Desk forms. Installation creates only app-owned DocTypes."""

def field(name, kind="Data", options=None, required=False, unique=False):
    value = {"fieldname": name, "label": name.replace("_", " ").title(),
             "fieldtype": kind, "reqd": int(required), "unique": int(unique)}
    if options:
        value["options"] = options
    return value


def link(name, target, required=False, unique=False):
    return field(name, "Link", target, required, unique)


